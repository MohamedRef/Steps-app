//! `steps-tools qbank sync --from FILE [--check]`: rebuilds
//! `content/qbank/uworld.yaml` from the plain-text export of the B&B ↔
//! UWorld QID doc and the hand-kept `content/qbank/bb-map.yaml`
//! (`steps_core::qbank`, docs/QBANK.md). `scripts/qbank-sync.sh` downloads
//! the export and runs this. `--check` only says whether the file is
//! current. Also the validate rule, [`problems`].

use std::collections::BTreeSet;
use std::path::Path;

use steps_core::qbank::{self, Map, QBank};

pub const SOURCE: &str = "bb-uworld";
pub const URL: &str = "https://docs.google.com/document/d/1LZweYMU5yXZIQtFl4AVpOo1-U9UQ6uRAo4mnu74Z2n4";

fn read_yaml<T: serde::de::DeserializeOwned>(path: &Path) -> Result<T, String> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    serde_yaml_ng::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))
}

fn lecture_order(root: &Path) -> Result<Vec<String>, String> {
    let index: steps_core::content::Index = read_yaml(&root.join("content/index.yaml"))?;
    Ok(index.lectures.into_iter().map(|l| l.id).collect())
}

pub fn run(root: &Path, args: &[String]) -> Result<String, Vec<String>> {
    if args.first().map(String::as_str) != Some("sync") {
        return Err(vec!["usage: steps-tools qbank sync --from EXPORT.txt [--check]".into()]);
    }
    let from =
        crate::flag(args, "--from").ok_or_else(|| vec!["--from EXPORT.txt is required".to_string()])?;
    let text = std::fs::read_to_string(from).map_err(|e| vec![format!("{from}: {e}")])?;
    let doc = qbank::parse_doc(&text).map_err(|e| vec![format!("{from}: {e}")])?;
    let map: Map = read_yaml(&root.join("content/qbank/bb-map.yaml")).map_err(|e| vec![e])?;
    let order = lecture_order(root).map_err(|e| vec![e])?;
    let order: Vec<&str> = order.iter().map(String::as_str).collect();
    let qb = qbank::build(&doc, &map, SOURCE, URL, &order)?;
    let out = root.join("content/qbank/uworld.yaml");
    let fresh = emit(&qb);
    let old = std::fs::read_to_string(&out).unwrap_or_default();
    let qids: usize = qb.lectures.iter().map(|l| l.count()).sum();
    let videos: usize = qb.lectures.iter().map(|l| l.sets.len()).sum();
    let summary = format!(
        "{videos} videos, {qids} QIDs in {} lectures, {} retired",
        qb.lectures.len(),
        qb.retired.len()
    );
    if args.iter().any(|a| a == "--check") {
        return if old == fresh {
            Ok(format!("uworld.yaml is current: {summary}"))
        } else {
            Err(vec![format!("uworld.yaml is out of date ({summary}): run scripts/qbank-sync.sh")])
        };
    }
    if old == fresh {
        return Ok(format!("no change: {summary}"));
    }
    std::fs::write(&out, fresh).map_err(|e| vec![format!("{}: {e}", out.display())])?;
    Ok(format!("updated content/qbank/uworld.yaml: {summary}"))
}

/// The file, one video per line, so a diff shows what moved.
pub fn emit(qb: &QBank) -> String {
    let list = |q: &[u32]| q.iter().map(u32::to_string).collect::<Vec<_>>().join(", ");
    let mut s = String::from(
        "# Generated by `scripts/qbank-sync.sh` (steps-tools qbank sync); do not edit.\n# UWorld Step 1 question IDs per First Aid lecture, by Boards and Beyond\n# video, from the public doc at `url`. Numbers only (docs/QBANK.md).\n",
    );
    s += &format!("schema: {}\nsource: {}\nurl: {}\nlectures:\n", qb.schema, qb.source, qb.url);
    for l in &qb.lectures {
        s += &format!("  - id: {}\n    sets:\n", l.id);
        for set in &l.sets {
            s += &format!(
                "      - {{ video: \"{}\", qids: [{}] }}\n",
                set.video.replace('"', "\\\""),
                list(&set.qids)
            );
        }
    }
    s += &format!("retired: [{}]\n", list(&qb.retired));
    s
}

/// The validate rule: the map's lectures exist, and no QID repeats.
pub fn problems(root: &Path, lectures: &BTreeSet<&str>, sources: &BTreeSet<String>) -> Vec<String> {
    let dir = root.join("content/qbank");
    if !dir.exists() {
        return Vec::new();
    }
    let (map, qb) =
        match (read_yaml::<Map>(&dir.join("bb-map.yaml")), read_yaml::<QBank>(&dir.join("uworld.yaml"))) {
            (Ok(m), Ok(q)) => (m, q),
            (m, q) => return m.err().into_iter().chain(q.err()).collect(),
        };
    let mut out: Vec<String> =
        qbank::problems(&map, &qb, lectures).into_iter().map(|p| format!("content/qbank/{p}")).collect();
    if !sources.contains(&qb.source) {
        out.push(format!("content/qbank/uworld.yaml: source {} is not in content/sources.yaml", qb.source));
    }
    if emit(&qb) != std::fs::read_to_string(dir.join("uworld.yaml")).unwrap_or_default() {
        out.push("content/qbank/uworld.yaml: edited by hand; run scripts/qbank-sync.sh instead".into());
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_file_reads_back_the_same() {
        let qb = QBank {
            schema: qbank::SCHEMA.into(),
            source: SOURCE.into(),
            url: URL.into(),
            lectures: vec![qbank::LectureSets {
                id: "cvs.L04".into(),
                sets: vec![
                    qbank::Set { video: "Cardiology › Atherosclerosis".into(), qids: vec![500, 501] },
                    qbank::Set { video: "Cardiology › STEMI".into(), qids: vec![] },
                ],
            }],
            retired: vec![7, 9],
        };
        let text = emit(&qb);
        assert_eq!(serde_yaml_ng::from_str::<QBank>(&text).unwrap(), qb);
    }
}
